function detectLang() {
  // 1️⃣ URL param ?lang=
  if (typeof location !== "undefined") {
    const params = new URLSearchParams(location.search);
    const fromUrl = params.get("lang");
    if (fromUrl && translations[fromUrl]) {
      return fromUrl;
    }
  }

  // 2️⃣ localStorage
  const saved = localStorage.getItem("lang");
  if (saved && translations[saved]) return saved;

  // 3️⃣ browser language
  const browser = (navigator.language || "es").toLowerCase();
  const short = browser.split("-")[0];
  if (translations[short]) return short;

  // 4️⃣ fallback
  return "es";
}

function getValue(lang, path) {
  const parts = path.split(".");
  let v = translations[lang];
  for (const k of parts) v = v && v[k];
  return v;
}

function syncLangButtons(activeLang) {
  const group = document.querySelector(".lang");
  if (group) {
    group.setAttribute("role", "group");
    group.setAttribute("aria-label", "Language selector");
  }

  document.querySelectorAll(".lang [data-lang]").forEach((b) => {
    const isActive = b.dataset.lang === activeLang;
    b.setAttribute("aria-pressed", isActive ? "true" : "false");
  });
}

function applyLang(lang) {
  if (!translations[lang]) lang = "es";
  document.documentElement.lang = lang;
  localStorage.setItem("lang", lang);

  const isDev =
    (typeof location !== "undefined" &&
      (location.hostname === "localhost" ||
        location.hostname === "127.0.0.1" ||
        location.hostname.endsWith(".test")));

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.dataset.i18n;
    const v = getValue(lang, key);

    if (typeof v === "string") {
      el.innerHTML = v;
      return;
    }

    if (isDev) {
      if (v === undefined) {
        console.warn("[i18n] Missing key", { lang, key, el });
      } else {
        console.warn("[i18n] Non-string value for key", {
          lang,
          key,
          valueType: typeof v,
          el
        });
      }
    }
  });

  document.querySelectorAll("[data-i18n-ph]").forEach((el) => {
    const key = el.dataset.i18nPh;
    const v = getValue(lang, key);

    if (typeof v === "string") {
      el.placeholder = v;
      return;
    }

    if (isDev) {
      if (v === undefined) {
        console.warn("[i18n] Missing placeholder key", { lang, key, el });
      } else {
        console.warn("[i18n] Non-string placeholder value for key", {
          lang,
          key,
          valueType: typeof v,
          el
        });
      }
    }
  });

  syncLangButtons(lang);
}

const lang = detectLang();
applyLang(lang);

document.querySelectorAll(".lang [data-lang]").forEach((b) => {
  b.onclick = () => applyLang(b.dataset.lang);
});
